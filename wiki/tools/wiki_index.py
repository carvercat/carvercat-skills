"""Build or check the Carvercat wiki indexes from page front matter.

    python3 wiki/tools/wiki_index.py          # check (exit 1 on any problem)
    python3 wiki/tools/wiki_index.py --write  # regenerate wiki/index.json and wiki/INDEX.md

A page is any .md under wiki/<section>/ (not README.md files). Front matter is a block between
'---' lines at the top, one `key: value` per line; lists are inline: `tags: [a, b]`.
Checks: required keys, id == path, unique ids, related ids exist, verified value, an
"## In Carvercat" section, relative links resolve, index.json and INDEX.md are current.
"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # wiki/
SECTIONS = ["principles", "design", "techniques", "sound-and-timing", "genres", "workflow", "accessibility", "history", "styles", "cookbook"]
TITLES = {"principles": "Principles of motion", "design": "Design fundamentals", "techniques": "Techniques",
          "sound-and-timing": "Sound and timing", "genres": "Genres", "workflow": "Workflow",
          "accessibility": "Accessibility", "history": "History and movements", "styles": "Styles",
          "cookbook": "Cookbook (how-to)"}
REQ = ["id", "title", "section", "tags", "styles", "topics", "related", "verified", "source_inspiration"]
VERIFIED = re.compile(r"^(0\.1\.6 \(rev 1105\)|design/1 \(Carvercat 0\.1\.\d+\)|no \(theory only\))$")
LISTS = {"tags", "styles", "topics", "related", "source_inspiration"}

def parse(path):
    txt = open(path, encoding="utf-8").read()
    if not txt.startswith("---\n"): return None, txt
    end = txt.index("\n---\n", 4)
    fm = {}
    for line in txt[4:end].splitlines():
        if not line.strip(): continue
        k, _, v = line.partition(":"); k, v = k.strip(), v.strip()
        if k in LISTS:
            v = v.strip("[]").strip()
            fm[k] = [x.strip().strip('"').strip("'") for x in v.split(",") if x.strip()] if v else []
        else:
            fm[k] = v.strip('"')
    return fm, txt[end + 5:]

def pages():
    out = []
    for sec in SECTIONS:
        d = os.path.join(ROOT, sec)
        if not os.path.isdir(d): continue
        for f in sorted(os.listdir(d)):
            if f.endswith(".md") and f != "README.md":
                out.append(os.path.join(d, f))
    return out

def build():
    recs, errs = [], []
    for p in pages():
        rel = os.path.relpath(p, ROOT).replace(os.sep, "/")
        fm, body = parse(p)
        if fm is None: errs.append(f"{rel}: no front matter"); continue
        for k in REQ:
            if k not in fm: errs.append(f"{rel}: missing {k}")
        if fm.get("id") != rel[:-3]: errs.append(f"{rel}: id {fm.get('id')!r} != {rel[:-3]!r}")
        if fm.get("section") != rel.split("/")[0]: errs.append(f"{rel}: section mismatch")
        if not VERIFIED.match(fm.get("verified", "")): errs.append(f"{rel}: bad verified {fm.get('verified')!r}")
        if "\n## In Carvercat" not in body: errs.append(f"{rel}: no '## In Carvercat' section")
        for u in fm.get("source_inspiration", []):
            if not u.startswith("https://") and not u.startswith("book:"): errs.append(f"{rel}: source not https/book: {u}")
        for m in re.finditer(r"\]\(([^)\s#]+)(#[^)\s]*)?\)", body):
            t = m.group(1)
            if re.match(r"^[a-z]+:", t): continue
            if not os.path.exists(os.path.normpath(os.path.join(os.path.dirname(p), t))): errs.append(f"{rel}: broken link {t}")
        recs.append({"id": fm.get("id"), "title": fm.get("title"), "path": "wiki/" + rel, "section": fm.get("section"),
                     "tags": fm.get("tags", []), "styles": fm.get("styles", []), "topics": fm.get("topics", []),
                     "related": fm.get("related", []), "verified": fm.get("verified"),
                     "source_inspiration": fm.get("source_inspiration", []), "words": len(body.split())})
    ids = [r["id"] for r in recs]
    for i in set(ids):
        if ids.count(i) > 1: errs.append(f"duplicate id {i}")
    for r in recs:
        for x in r["related"]:
            if x not in ids: errs.append(f"{r['id']}: related {x} is not a page")
    return recs, errs

def render(recs):
    idx = {"schema": 1, "about": "Carvercat motion-design wiki: one record per page. Generated by wiki/tools/wiki_index.py --write; do not edit by hand.",
           "count": len(recs), "verified_count": sum(1 for r in recs if r["verified"] != "no (theory only)"), "pages": recs}
    j = json.dumps(idx, indent=1, ensure_ascii=False) + "\n"
    md = ["# Wiki index", "", "Generated by `wiki/tools/wiki_index.py --write` from each page's front matter; do not edit by hand. "
          "Machine-readable twin: [index.json](index.json). Front page: [README.md](README.md). Terms: [glossary.md](glossary.md).", "",
          f"{len(recs)} pages, {idx['verified_count']} with values measured in Carvercat (0.1.6, rev 1105,; newer pages on design/1, Carvercat 0.1.8). Calls and units are design units on every page.", ""]
    for sec in SECTIONS:
        rs = [r for r in recs if r["section"] == sec]
        if not rs: continue
        md += [f"## {TITLES[sec]}", "", "| Page | Topics | Styles | Verified |", "|---|---|---|---|"]
        for r in rs:
            v = "theory" if r["verified"] == "no (theory only)" else ("design/1" if r["verified"].startswith("design/1") else "0.1.6")
            md.append(f"| [{r['title']}]({r['path'][5:]}) | {', '.join(r['topics'])} | {', '.join(r['styles'])} | {v} |")
        md.append("")
    return j, "\n".join(md)

if __name__ == "__main__":
    recs, errs = build()
    j, md = render(recs)
    if "--write" in sys.argv:
        open(os.path.join(ROOT, "index.json"), "w", encoding="utf-8").write(j)
        open(os.path.join(ROOT, "INDEX.md"), "w", encoding="utf-8").write(md)
    else:
        for name, want in (("index.json", j), ("INDEX.md", md)):
            p = os.path.join(ROOT, name)
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != want: errs.append(f"{name} is stale: run --write")
    for e in errs: print(e)
    print(f"{len(recs)} pages, {len(errs)} problem(s)")
    sys.exit(1 if errs else 0)
