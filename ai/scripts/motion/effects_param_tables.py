"""Generate ai/references/effects/PARAMETERS.md from ai/references/app/native-controls.json.

    python effects_param_tables.py            # writes the file
    python effects_param_tables.py --check    # exit 1 if it is stale

native-controls.json is the app registry snapshot (refresh it with
tools/build_native_controls.py --app PATH). This table is discovery data:
a declared parameter is not proof that it renders, so the effect guides say
what was actually verified.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.normpath(os.path.join(HERE, "..", "..", "references"))
SRC = os.path.join(REF, "app", "native-controls.json")
OUT = os.path.join(REF, "effects", "PARAMETERS.md")

GROUPS = [
    ("Effects (added with `effect.add {cap}`)", ["blur", "glow", "shadow", "motionblur", "fill", "stroke", "colour", "transform", "crop", "outline", "expand", "stylelayer", "trim"]),
    ("Shape paint and geometry", ["shape.fill", "shape.stroke", "shape.geometry.rectangle", "shape.geometry.line", "shape.geometry.ellipse", "shape.geometry.ngon", "shape.geometry.star"]),
    ("Text", ["text.content", "text.font", "text.fill", "text.outline", "text.relative", "text.layout", "text.decoration", "text.typography"]),
    ("Transform, compositing, masks, parenting, media", ["transform.placement", "transform.compositing", "mask", "parent", "media.trim"]),
]

def fmt(v):
    if v is None: return ""
    if isinstance(v, float): return f"{v:g}"
    if isinstance(v, list): return "[" + ", ".join(fmt(x) for x in v) + "]"
    return str(v)

def render():
    d = json.load(open(SRC, encoding="utf-8"))
    caps = d["caps"]
    out = ["# Native parameters by capability (generated)", "",
           f"Generated by `ai/scripts/motion/effects_param_tables.py` from `native-controls.json` "
           f"(registry {d.get('registrySha256','?')[:12]}). Do not edit by hand. A declared parameter is discovery data, not proof "
           "that it renders. The effect guides in this folder say what was verified. Use these names with `property.set`/`key.set` "
           "on the stored path that `param.list` prints (`fx.<entry>.<param>`), or with batch `{\"$param\":[alias, param]}`.", ""]
    seen = set()
    for title, keys in GROUPS:
        out += [f"## {title}", ""]
        for k in keys:
            if k not in caps: continue
            seen.add(k)
            out += [f"### `{k}`", "", "| param | label | type | range | default | options | keys |", "|---|---|---|---|---|---|---|"]
            for p in caps[k]:
                rng = "" if p.get("min") is None and p.get("max") is None else f"{fmt(p.get('min'))}..{fmt(p.get('max'))}"
                opts = ", ".join(map(str, p.get("options") or []))
                out.append(f"| {p.get('param')} | {p.get('label','')} | {p.get('type','')} | {rng} | {fmt(p.get('default'))} | {opts} | {'yes' if p.get('keyframeable') else 'no'} |")
            out.append("")
    rest = [k for k in caps if k not in seen]
    if rest:
        out += ["## Other", ""] + [f"- `{k}`" for k in rest]
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == text else 1)
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote", OUT, len(text.splitlines()), "lines")
